const express = require('express');
const { authRequired } = require('../../middlewares/auth.middleware');
const { permissionRequired } = require('../../middlewares/permission.middleware');
const { validate } = require('../../middlewares/validate.middleware');
const controller = require('../../controllers/pqrs/pqrs.controller');
const stats = require('../../controllers/pqrs/pqrsStats.controller');
const responses = require('../../controllers/pqrs/response.controller');
const validator = require('../../validators/pqrs.validator');
const responseValidator = require('../../validators/pqrsResponse.validator');
const router = express.Router();
router.get('/stats', authRequired, stats.stats);
router.get('/', authRequired, permissionRequired('PQRS', 'view'), validate(validator.query), controller.list);
router.post('/', authRequired, permissionRequired('PQRS', 'create'), validate(validator.create), controller.create);
router.get('/:id/responses', authRequired, permissionRequired('PQRS', 'view'), validate(responseValidator.params), responses.getResponses);
router.post('/:id/responses', authRequired, permissionRequired('PQRS', 'view'), validate(responseValidator.create), responses.createResponse);
router.patch('/:id/status', authRequired, permissionRequired('PQRS', 'edit'), validate(validator.status), controller.updateStatus);
router.patch('/:id/assign', authRequired, permissionRequired('PQRS', 'edit'), validate(validator.assign), controller.assign);
router.delete('/:id', authRequired, controller.remove);
router.get('/:id', authRequired, permissionRequired('PQRS', 'view'), controller.get);
module.exports = router;
