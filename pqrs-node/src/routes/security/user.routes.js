const express = require('express');
const { authRequired } = require('../../middlewares/auth.middleware');
const { permissionRequired } = require('../../middlewares/permission.middleware');
const { validate } = require('../../middlewares/validate.middleware');
const users = require('../../controllers/security/user.controller');
const profiles = require('../../controllers/security/profile.controller');
const validators = require('../../validators/user.validator');
const router = express.Router();
router.get('/:id/profile', authRequired, permissionRequired('Perfiles', 'view'), profiles.getForUser);
router.put('/:id/profile', authRequired, permissionRequired('Perfiles', 'edit'), validate(require('../../validators/profile.validator').update), profiles.updateForUser);
router.get('/', authRequired, permissionRequired('Usuarios', 'view'), users.list);
router.post('/', authRequired, permissionRequired('Usuarios', 'create'), validate(validators.create), users.create);
router.get('/:id/roles', authRequired, permissionRequired('Usuarios', 'view'), users.listRoles);
router.post('/:id/roles', authRequired, permissionRequired('Usuarios', 'edit'), validate(validators.role), users.assignRole);
router.delete('/:id/roles/:urId', authRequired, permissionRequired('Usuarios', 'edit'), users.revokeRole);
router.patch('/:id/status', authRequired, permissionRequired('Usuarios', 'edit'), validate(validators.status), users.updateStatus);
router.patch('/:id/password', authRequired, permissionRequired('Usuarios', 'edit'), validate(validators.password), users.updatePassword);
router.get('/:id', authRequired, permissionRequired('Usuarios', 'view'), users.get);
router.put('/:id', authRequired, permissionRequired('Usuarios', 'edit'), validate(validators.update), users.update);
router.delete('/:id', authRequired, permissionRequired('Usuarios', 'delete'), users.deleteUser);
module.exports = router;
