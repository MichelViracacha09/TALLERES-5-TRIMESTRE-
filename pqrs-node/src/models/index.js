const { DataTypes } = require('sequelize');
const { sequelize } = require('../config/database');
const UserStatus = require('./UserStatus')(sequelize, DataTypes);
const DocumentType = require('./DocumentType')(sequelize, DataTypes);
const Role = require('./Role')(sequelize, DataTypes);
const Permission = require('./Permission')(sequelize, DataTypes);
const Module = require('./Module')(sequelize, DataTypes);
const PqrsType = require('./PqrsType')(sequelize, DataTypes);
const PqrsStatus = require('./PqrsStatus')(sequelize, DataTypes);
const User = require('./User')(sequelize, DataTypes);
const UserRole = require('./UserRole')(sequelize, DataTypes);
const RoleModulePermission = require('./RoleModulePermission')(sequelize, DataTypes);
const Profile = require('./Profile')(sequelize, DataTypes);
const Pqrs = require('./Pqrs')(sequelize, DataTypes);
const PqrsResponse = require('./PqrsResponse')(sequelize, DataTypes);

User.belongsTo(UserStatus, { as: 'status', foreignKey: 'statusId' });
User.hasOne(Profile, { as: 'profile', foreignKey: 'userId' });
Profile.belongsTo(User, { as: 'user', foreignKey: 'userId' });
Profile.belongsTo(DocumentType, { as: 'document_type', foreignKey: 'documentTypeId' });
User.hasMany(UserRole, { as: 'user_roles', foreignKey: 'userId' });
UserRole.belongsTo(User, { as: 'user', foreignKey: 'userId' });
UserRole.belongsTo(Role, { as: 'role', foreignKey: 'roleId' });
UserRole.belongsTo(UserStatus, { as: 'status', foreignKey: 'statusId' });
Role.hasMany(UserRole, { as: 'user_roles', foreignKey: 'roleId' });
Role.hasMany(RoleModulePermission, { as: 'role_module_permissions', foreignKey: 'roleId' });
Module.hasMany(RoleModulePermission, { as: 'role_module_permissions', foreignKey: 'moduleId' });
Permission.hasMany(RoleModulePermission, { as: 'role_module_permissions', foreignKey: 'permissionId' });
RoleModulePermission.belongsTo(Role, { as: 'role', foreignKey: 'roleId' });
RoleModulePermission.belongsTo(Module, { as: 'module', foreignKey: 'moduleId' });
RoleModulePermission.belongsTo(Permission, { as: 'permission', foreignKey: 'permissionId' });
User.hasMany(Pqrs, { as: 'created_pqrs', foreignKey: 'userId' });
User.hasMany(Pqrs, { as: 'assigned_pqrs', foreignKey: 'assignedTo' });
Pqrs.belongsTo(User, { as: 'creator', foreignKey: 'userId' });
Pqrs.belongsTo(User, { as: 'assignee', foreignKey: 'assignedTo' });
Pqrs.belongsTo(PqrsType, { as: 'type', foreignKey: 'pqrsTypeId' });
Pqrs.belongsTo(PqrsStatus, { as: 'status', foreignKey: 'pqrsStatusId' });
Pqrs.hasMany(PqrsResponse, { as: 'responses', foreignKey: 'pqrsId' });
PqrsResponse.belongsTo(Pqrs, { as: 'pqrs', foreignKey: 'pqrsId' });
PqrsResponse.belongsTo(User, { as: 'user', foreignKey: 'userId' });

module.exports = { sequelize, UserStatus, DocumentType, Role, Permission, Module, PqrsType, PqrsStatus, User, UserRole, RoleModulePermission, Profile, Pqrs, PqrsResponse };
